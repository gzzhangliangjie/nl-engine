// 几何汇集：.glb -> loadGltfScene 全 primitive；.nmesh -> fallback 段
bool loadGeometry(const char* path, nl::nav::Geometry& geo, std::string& err) {
    const std::string p = path;
    if (p.size() > 4 && p.compare(p.size() - 4, 4, ".glb") == 0) {
        nl::core::SceneMeshData scene;
        if (!nl::core::loadGltfScene(path, scene, err)) return false;
        for (const nl::core::PrimitiveMesh& m : scene.meshes) {
            const std::uint32_t base = static_cast<std::uint32_t>(
                geo.verts.size() / 3);
            for (const nl::core::MeshVertex& v : m.vertices)
                geo.verts.insert(geo.verts.end(), v.pos, v.pos + 3);
            for (const std::uint32_t idx : m.indices)
                geo.tris.push_back(base + idx);
        }
        return !geo.tris.empty();
    }
    if (p.size() > 6 && p.compare(p.size() - 6, 6, ".nmesh") == 0) {
        nl::core::NMeshData data;
        if (!nl::core::loadNMesh(path, data, err)) return false;
        if (!data.fallbackPresent) {
            err = std::string(path) +
                  ": no fallback section (v1 base); bake needs v3 .nmesh with "
                  "fallback or a .glb";
            return false;
        }
        for (const nl::core::MeshVertex& v : data.fallbackVertices)
            geo.verts.insert(geo.verts.end(), v.pos, v.pos + 3);
        geo.tris = data.fallbackIndices;
        return !geo.tris.empty();
    }
    err = "unsupported input (expect .glb or .nmesh): " + p;
    return false;
}

