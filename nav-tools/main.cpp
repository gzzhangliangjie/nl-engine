// 俯视正交线框画布（x→右，z→下，等比 + 32px 边距居中）。wire 与 query --png
// 共用同一投影口径；Bresenham 逐像素确定性遍历（M-N0 wire 口径不变）。
struct WireCanvas {
    std::vector<unsigned char> rgb;
    int   size  = 0;
    float scale = 0.f, cx = 0.f, cz = 0.f;
    int   edgeCount = 0;

    void toPx(float x, float z, int& px, int& py) const {
        px = static_cast<int>(std::lround((x - cx) * scale)) + size / 2;
        py = static_cast<int>(std::lround((z - cz) * scale)) + size / 2;
    }
    void dot(int px, int py, unsigned char r, unsigned char g, unsigned char b) {
        if (px < 0 || px >= size || py < 0 || py >= size) return;
        const size_t o = (static_cast<size_t>(py) * size + px) * 3;
        rgb[o] = r; rgb[o + 1] = g; rgb[o + 2] = b;
    }
    void line(float ax, float az, float bx, float bz,
              unsigned char r, unsigned char g, unsigned char b) {
        int x0, y0, x1, y1;
        toPx(ax, az, x0, y0);
        toPx(bx, bz, x1, y1);
        int dx = std::abs(x1 - x0), sx = x0 < x1 ? 1 : -1;
        int dy = -std::abs(y1 - y0), sy = y0 < y1 ? 1 : -1;
        int e = dx + dy;
        for (;;) {
            dot(x0, y0, r, g, b);
            if (x0 == x1 && y0 == y1) break;
            const int e2 = 2 * e;
            if (e2 >= dy) { e += dy; x0 += sx; }
            if (e2 <= dx) { e += dx; y0 += sy; }
        }
    }
    // 十字标记（半径 2px）——起/终点
    void cross(float x, float z, unsigned char r, unsigned char g,
               unsigned char b) {
        int px, py;
        toPx(x, z, px, py);
        for (int d = -2; d <= 2; ++d) {
            dot(px + d, py, r, g, b);
            dot(px, py + d, r, g, b);
        }
    }
    // M-N2：alpha 感知写像素（duRGBA a<255 与白底混合；a=255 直接覆盖）。
    // 绘制顺序 = 图元流顺序（确定性硬判据：同输入同字节）。
    void blendDot(int px, int py, unsigned int col) {
        if (px < 0 || px >= size || py < 0 || py >= size) return;
        const unsigned int a = (col >> 24) & 0xFF;
        const size_t o = (static_cast<size_t>(py) * size + px) * 3;
        if (a >= 255) {
            rgb[o]     = static_cast<unsigned char>(col & 0xFF);
            rgb[o + 1] = static_cast<unsigned char>((col >> 8) & 0xFF);
            rgb[o + 2] = static_cast<unsigned char>((col >> 16) & 0xFF);
            return;
        }
        for (int k = 0; k < 3; ++k) {
            const unsigned int dst = rgb[o + k];
            const unsigned int src = (col >> (8 * k)) & 0xFF;
            rgb[o + k] = static_cast<unsigned char>(
                (src * a + dst * (255 - a)) / 255);
        }
    }
    // 三角填充：包围盒 + 边函数（归一方向），w >= -0.5 容差收共享边缝
    //（双绘无害——填充是覆盖语义）。整数像素坐标上浮点边函数结果确定。
    void tri(float ax, float az, float bx, float bz, float cx, float cz,
             unsigned int col) {
        int x0, y0, x1, y1, x2, y2;
        toPx(ax, az, x0, y0);
        toPx(bx, bz, x1, y1);
        toPx(cx, cz, x2, y2);
        const float area = static_cast<float>(
            (x1 - x0) * (y2 - y0) - (y1 - y0) * (x2 - x0));
        if (std::fabs(area) < 1e-6f) return;  // 退化（共线/出画布缩没）
        const float sign = area > 0.f ? 1.f : -1.f;
        const int minx = std::max(0, std::min({x0, x1, x2}));
        const int maxx = std::min(size - 1, std::max({x0, x1, x2}));
        const int miny = std::max(0, std::min({y0, y1, y2}));
        const int maxy = std::min(size - 1, std::max({y0, y1, y2}));
        auto edge = [sign](int axi, int ayi, int bxi, int byi, int px, int py) {
            return static_cast<float>((bxi - axi) * (py - ayi) -
                                      (byi - ayi) * (px - axi)) * sign;
        };
        for (int py = miny; py <= maxy; ++py) {
            for (int px = minx; px <= maxx; ++px) {
                const float w0 = edge(x1, y1, x2, y2, px, py);
                const float w1 = edge(x2, y2, x0, y0, px, py);
                const float w2 = edge(x0, y0, x1, y1, px, py);
                if (w0 >= -0.5f && w1 >= -0.5f && w2 >= -0.5f)
                    blendDot(px, py, col);
            }
        }
    }
};

bool makeWireCanvas(const nl::nav::NavMesh& nav, int size, WireCanvas& out) {
    const std::vector<nl::nav::NavMesh::Edge> edges = nav.polyEdges();
    out = WireCanvas{};
    out.edgeCount = static_cast<int>(edges.size());
    out.size      = size;
    const nl::nav::BuildStats& s = nav.stats();
    const float spanX = s.bmax[0] - s.bmin[0];
    const float spanZ = s.bmax[2] - s.bmin[2];
    const float span  = spanX > spanZ ? spanX : spanZ;
    if (span <= 0.f) return false;
    const int   margin = 32;
    out.scale = static_cast<float>(size - 2 * margin) / span;
    out.cx    = (s.bmin[0] + s.bmax[0]) * 0.5f;
    out.cz    = (s.bmin[2] + s.bmax[2]) * 0.5f;
    out.rgb.assign(static_cast<size_t>(size) * size * 3, 247);
    for (const nl::nav::NavMesh::Edge& e : edges)
        out.line(e.a[0], e.a[2], e.b[0], e.b[2], 52, 52, 52);
    return true;
}

int cmdWire(int argc, char** argv) {
    if (argc < 2) { usage(); return 2; }
    const char* inPath  = argv[0];
    const char* outPath = argv[1];
    int size = 1024;
    std::string err;
    for (int i = 2; i < argc; ++i) {
        if (std::strcmp(argv[i], "--size") == 0 && i + 1 < argc) {
            size = std::atoi(argv[++i]);
        } else {
            std::printf("nav-tools wire: unknown option: %s\n", argv[i]);
            return 2;
        }
    }
    if (size < 64 || size > 4096) {
        std::printf("nav-tools wire: --size must be in [64, 4096]\n");
        return 2;
    }

    nl::nav::NavMesh nav;
    if (!nav.load(inPath, err)) {
        std::printf("nav-tools wire: %s\n", err.c_str());
        return 1;
    }
    WireCanvas canvas;
    if (!makeWireCanvas(nav, size, canvas)) {
        std::printf("nav-tools wire: degenerate bounds\n");
        return 1;
    }
    if (canvas.edgeCount == 0) {
        std::printf("nav-tools wire: no polygons\n");
        return 1;
    }
    if (!png::write(outPath, size, size, canvas.rgb, err)) {
        std::printf("nav-tools wire: %s\n", err.c_str());
        return 1;
    }
    std::printf("input       : %s\n", inPath);
    std::printf("edges       : %d\n", canvas.edgeCount);
    std::printf("view        : top-down orthographic (x right, z down)\n");
    std::printf("canvas      : %dx%d\n", size, size);
    std::printf("saved       : %s\n", outPath);
    return 0;
}

// ---------------------------------------------------------------------------
// M-N2：debug-stage —— 五阶段叠加图（bake keepDebug -> debugDrawStage 收集 ->
// 俯视软光栅 PNG）。证据图取工具真实输出（P8-NAV-PLAN 拍板口径）。
bool makePrimCanvas(const nl::nav::NavMesh& nav, int size, WireCanvas& out) {
    out = WireCanvas{};
    out.size = size;
    const nl::nav::BuildStats& s = nav.stats();
    const float spanX = s.bmax[0] - s.bmin[0];
    const float spanZ = s.bmax[2] - s.bmin[2];
    const float span  = spanX > spanZ ? spanX : spanZ;
    if (span <= 0.f) return false;
    const int   margin = 32;
    out.scale = static_cast<float>(size - 2 * margin) / span;
    out.cx    = (s.bmin[0] + s.bmax[0]) * 0.5f;
    out.cz    = (s.bmin[2] + s.bmax[2]) * 0.5f;
    out.rgb.assign(static_cast<size_t>(size) * size * 3, 247);
    return true;
}

int cmdDebugStage(int argc, char** argv) {
    if (argc < 2) { usage(); return 2; }
    const char* inPath  = argv[0];
    const char* outPath = argv[1];
    nl::nav::DebugStage stage;
    if (argc > 2 && std::strcmp(argv[2], "--stage") == 0 && argc > 3) {
        if (!nl::nav::debugStageFromName(argv[3], stage)) {
            std::printf("nav-tools debug-stage: unknown --stage '%s' "
                        "(voxels|regions|distance|contours|raw-contours|"
                        "polymesh|navmesh)\n", argv[3]);
            return 2;
        }
    } else {
        std::printf("nav-tools debug-stage: --stage is required\n");
        return 2;
    }
    int size = 1024;
    BakeOptions opt;
    std::string err;
    int i = 4;
    for (; i < argc; ++i) {
        const std::string a = argv[i];
        if (a == "--size") {
            if (i + 1 >= argc) { std::printf("nav-tools debug-stage: --size needs a value\n"); return 2; }
            size = std::atoi(argv[++i]);
        } else {
            // 交给 bake 参数解析器从当前位吃（--cell-size 等）
            if (!parseBakeArgs(argc, argv, i, opt, err)) {
                std::printf("nav-tools debug-stage: %s\n", err.c_str());
                return 2;
            }
            break;
        }
    }
    if (size < 64 || size > 4096) {
        std::printf("nav-tools debug-stage: --size must be in [64, 4096]\n");
        return 2;
    }

    nl::nav::Geometry geo;
    if (!loadGeometry(inPath, geo, err)) {
        std::printf("nav-tools debug-stage: geometry load failed: %s\n", err.c_str());
        return 1;
    }
    nl::nav::NavMesh nav;
    if (!nav.bake(geo, opt.params, err, /*keepDebug=*/true)) {
        std::printf("nav-tools debug-stage: bake failed: %s\n", err.c_str());
        return 1;
    }
    nl::nav::DebugPrims prims;
    if (!nav.debugDrawStage(stage, prims, err)) {
        std::printf("nav-tools debug-stage: %s\n", err.c_str());
        return 1;
    }

    WireCanvas canvas;
    if (!makePrimCanvas(nav, size, canvas)) {
        std::printf("nav-tools debug-stage: degenerate bounds\n");
        return 1;
    }
    int groupCount = 0;
    for (const nl::nav::DebugPrims::Group& g : prims.groups) {
        const int n = g.vertEnd - g.vertBegin;
        if (n <= 0) continue;
        ++groupCount;
        if (g.prim == nl::nav::DebugPrims::POINTS) {
            for (int v = g.vertBegin; v < g.vertEnd; ++v) {
                int px, py;
                canvas.toPx(prims.verts[v].pos[0], prims.verts[v].pos[2], px, py);
                for (int d = -1; d <= 1; ++d) {
                    canvas.blendDot(px + d, py, prims.verts[v].col);
                    canvas.blendDot(px, py + d, prims.verts[v].col);
                }
            }
        } else if (g.prim == nl::nav::DebugPrims::LINES) {
            for (int v = g.vertBegin; v + 1 < g.vertEnd; v += 2) {
                int x0, y0, x1, y1;
                canvas.toPx(prims.verts[v].pos[0],     prims.verts[v].pos[2],     x0, y0);
                canvas.toPx(prims.verts[v + 1].pos[0], prims.verts[v + 1].pos[2], x1, y1);
                // Bresenham + blendDot（逐像素确定性遍历）
                int dx = std::abs(x1 - x0), sx = x0 < x1 ? 1 : -1;
                int dy = -std::abs(y1 - y0), sy = y0 < y1 ? 1 : -1;
                int e = dx + dy;
                for (;;) {
                    canvas.blendDot(x0, y0, prims.verts[v].col);
                    if (x0 == x1 && y0 == y1) break;
                    const int e2 = 2 * e;
                    if (e2 >= dy) { e += dy; x0 += sx; }
                    if (e2 <= dx) { e += dx; y0 += sy; }
                }
            }
        } else if (g.prim == nl::nav::DebugPrims::TRIS) {
            for (int v = g.vertBegin; v + 2 < g.vertEnd; v += 3)
                canvas.tri(prims.verts[v].pos[0],     prims.verts[v].pos[2],
                           prims.verts[v + 1].pos[0], prims.verts[v + 1].pos[2],
                           prims.verts[v + 2].pos[0], prims.verts[v + 2].pos[2],
                           prims.verts[v].col);
        } else if (g.prim == nl::nav::DebugPrims::QUADS) {
            for (int v = g.vertBegin; v + 3 < g.vertEnd; v += 4) {
                const auto& A = prims.verts[v];
                const auto& B = prims.verts[v + 1];
                const auto& C = prims.verts[v + 2];
                const auto& D = prims.verts[v + 3];
                canvas.tri(A.pos[0], A.pos[2], B.pos[0], B.pos[2],
                           C.pos[0], C.pos[2], A.col);
                canvas.tri(A.pos[0], A.pos[2], C.pos[0], C.pos[2],
                           D.pos[0], D.pos[2], A.col);
            }
        }
    }
    if (!png::write(outPath, size, size, canvas.rgb, err)) {
        std::printf("nav-tools debug-stage: %s\n", err.c_str());
        return 1;
    }
    const nl::nav::BuildStats& s = nav.stats();
    std::printf("input       : %s\n", inPath);
    std::printf("stage       : %s\n", nl::nav::debugStageName(stage));
    std::printf("groups      : %d\n", groupCount);
    std::printf("prims       : %zu groups / %zu verts\n",
                prims.groups.size(), prims.verts.size());
    std::printf("polys       : %d | compact spans: %d | regions: %d\n",
                s.polyCount, s.compactSpans, s.regionCount);
    std::printf("view        : top-down orthographic (x right, z down)\n");
    std::printf("canvas      : %dx%d\n", size, size);
    std::printf("saved       : %s\n", outPath);
    return 0;
}

