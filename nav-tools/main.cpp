// nav-tools — P8 M-N0 NavMesh bake/dump headless acceptance tool
// (A-class parallel track). Only links nl_core (nl/nav + mesh_io +
// meshlet_io); zero graphics API symbols, no GPU, no kStage, no rendering
// regression.
//
// Exit code contract (aligned with phys-tools / anim-tools, showcase expectExit):
//   0 = PASS            1 = assertion / runtime failure            2 = usage error
//
// Subcommands:
//   bake <in.glb|.nmesh> <out.nnav> [--cell-size F] [--cell-height F]
//        [--slope F] [--agent-height F] [--agent-radius F] [--agent-climb F]
//                          bake NavMesh from mesh geometry (glTF primitives or
//                          .nmesh fallback section), save container "NLNV"
//   dump <in.nnav>         load + stats (polys/verts/area/bounds/fnv64)
//   wire <in.nnav> <out.png> [--size N]
//                          top-down orthographic poly-boundary wireframe PNG
//                          (real tool output, evidence rule: no hand-drawing)
//   query <in.nnav> --start x,y,z --end x,y,z [--max-nodes N]
//        [--max-waypoints N] [--half-extents x,y,z] [--png out.png]
//                          M-N1: findNearestPoly -> findPath -> findStraightPath;
//                          prints status (OK/UNREACHABLE/OUT_OF_NODES/
//                          BUFFER_TOO_SMALL/...) + waypoints; exit 0=reachable,
//                          1=negative query result, 2=usage error
//   resave <in.nnav> <out.nnav>
//   selftest [--verbose]   mechanical anchors: synthetic bake, determinism
//                          (byte-identical artifacts), save/load roundtrip,
//                          negative inputs, M-N1 query anchors
//
// Evidence rule: example/nav-m0/*.png is generated by `nav-tools wire` from the
// REAL bake artifact. No hand-drawn diagrams.

