// M-N1：query —— findNearestPoly -> findPath -> findStraightPath 完整链
bool parseVec3(const char* s, float v[3]) {
    if (!s) return false;
    return std::sscanf(s, "%f,%f,%f", &v[0], &v[1], &v[2]) == 3 &&
           std::isfinite(v[0]) && std::isfinite(v[1]) && std::isfinite(v[2]);
}

int cmdQuery(int argc, char** argv) {
    if (argc < 1) { usage(); return 2; }
    const char* inPath = argv[0];
    float start[3] = {0, 0, 0}, end[3] = {0, 0, 0};
    bool haveStart = false, haveEnd = false;
    nl::nav::NavMesh::QueryParams qp;
    const char* pngPath  = nullptr;
    int pngSize          = 1024;
    std::string err;
    for (int i = 1; i < argc; ++i) {
        const std::string a = argv[i];
        auto needVal = [&]() -> const char* {
            if (i + 1 >= argc) return nullptr;
            return argv[++i];
        };
        if (a == "--start") {
            const char* v = needVal();
            if (!v || !parseVec3(v, start)) {
                std::printf("nav-tools query: --start needs x,y,z\n");
                return 2;
            }
            haveStart = true;
        } else if (a == "--end") {
            const char* v = needVal();
            if (!v || !parseVec3(v, end)) {
                std::printf("nav-tools query: --end needs x,y,z\n");
                return 2;
            }
            haveEnd = true;
        } else if (a == "--max-nodes") {
            const char* v = needVal();
            if (!v || (qp.maxNodes = std::atoi(v)) < 4 || qp.maxNodes > 65535) {
                std::printf("nav-tools query: --max-nodes must be in [4, 65535]\n");
                return 2;
            }
        } else if (a == "--max-waypoints") {
            const char* v = needVal();
            if (!v || (qp.maxWaypoints = std::atoi(v)) <= 0) {
                std::printf("nav-tools query: --max-waypoints must be >= 1\n");
                return 2;
            }
        } else if (a == "--half-extents") {
            const char* v = needVal();
            if (!v || !parseVec3(v, qp.halfExtents) || qp.halfExtents[0] <= 0.f ||
                qp.halfExtents[1] <= 0.f || qp.halfExtents[2] <= 0.f) {
                std::printf("nav-tools query: --half-extents needs x,y,z > 0\n");
                return 2;
            }
        } else if (a == "--png") {
            pngPath = needVal();
            if (!pngPath) {
                std::printf("nav-tools query: --png needs a path\n");
                return 2;
            }
        } else if (a == "--size") {
            const char* v = needVal();
            if (!v || (pngSize = std::atoi(v)) < 64 || pngSize > 4096) {
                std::printf("nav-tools query: --size must be in [64, 4096]\n");
                return 2;
            }
        } else {
            std::printf("nav-tools query: unknown option: %s\n", argv[i]);
            return 2;
        }
    }
    if (!haveStart || !haveEnd) {
        std::printf("nav-tools query: --start and --end are required\n");
        return 2;
    }

    nl::nav::NavMesh nav;
    if (!nav.load(inPath, err)) {
        std::printf("nav-tools query: %s\n", err.c_str());
        return 1;
    }

    nl::nav::NavMesh::QueryResult r;
    const nl::nav::NavMesh::QueryStatus st =
        nav.findPath(start, end, qp, r);
    const int nWp = static_cast<int>(r.waypoints.size() / 3);

    std::printf("navmesh     : %s\n", inPath);
    std::printf("start       : (%.3f, %.3f, %.3f)\n", start[0], start[1],
                start[2]);
    std::printf("end         : (%.3f, %.3f, %.3f)\n", end[0], end[1], end[2]);
    std::printf("maxNodes    : %d\n", qp.maxNodes);
    std::printf("status      : %s\n",
                nl::nav::NavMesh::queryStatusName(st));
    std::printf("reachedLimit: %d\n", r.reachedLimit ? 1 : 0);
    std::printf("waypoints   : %d\n", nWp);
    for (int i = 0; i < nWp; ++i) {
        std::printf("  wp[%d]     : (%.3f, %.3f, %.3f)\n", i,
                    r.waypoints[i * 3], r.waypoints[i * 3 + 1],
                    r.waypoints[i * 3 + 2]);
    }

    if (pngPath) {
        WireCanvas canvas;
        if (!makeWireCanvas(nav, pngSize, canvas)) {
            std::printf("nav-tools query: degenerate bounds (no png)\n");
            return 1;
        }
        // 折线（红）+ 起点十字（蓝）+ 折线末端十字（绿：吸附后的实际到达点，
        // UNREACHABLE 时为 best-effort 前缀终点——证据图如实反映）
        for (int i = 1; i < nWp; ++i)
            canvas.line(r.waypoints[(i - 1) * 3], r.waypoints[(i - 1) * 3 + 2],
                        r.waypoints[i * 3], r.waypoints[i * 3 + 2],
                        220, 40, 40);
        if (nWp > 0) {
            // 十字标折线两端（吸附后的实际起讫点；原始 start/end 坐标在 log）
            canvas.cross(r.waypoints[0], r.waypoints[2], 40, 80, 220);
            canvas.cross(r.waypoints[(nWp - 1) * 3],
                         r.waypoints[(nWp - 1) * 3 + 2], 40, 180, 60);
        }
        if (!png::write(pngPath, canvas.size, canvas.size, canvas.rgb, err)) {
            std::printf("nav-tools query: %s\n", err.c_str());
            return 1;
        }
        std::printf("png         : %s (%dx%d)\n", pngPath, canvas.size,
                    canvas.size);
    }

    switch (st) {
    case nl::nav::NavMesh::QueryStatus::OK: return 0;
    case nl::nav::NavMesh::QueryStatus::UNREACHABLE:
    case nl::nav::NavMesh::QueryStatus::OUT_OF_NODES:
    case nl::nav::NavMesh::QueryStatus::BUFFER_TOO_SMALL:
        return 1;
    default:
        return 2; // INVALID_PARAM / NOT_INITIALIZED = 用法级错误
    }
}

// ---------------------------------------------------------------------------
// selftest：合成场景锚点
// 场景 = 20x20 地板 + 中央 2x2x2 方块障碍（角色须绕行 → 中心区不可走）+
// 30° 缓坡一条（可走）。确定性锚点：两次 bake 产物逐字节一致 + roundtrip 一致。
nl::nav::Geometry syntheticScene() {
    nl::nav::Geometry g;
    auto quad = [&](float x0, float z0, float x1, float z1, float y) {
        const std::uint32_t base = static_cast<std::uint32_t>(g.verts.size() / 3);
        const float v[4][3] = {{x0, y, z0}, {x1, y, z0}, {x1, y, z1}, {x0, y, z1}};
        for (int i = 0; i < 4; ++i)
            g.verts.insert(g.verts.end(), v[i], v[i] + 3);
        // 俯视 CCW（法线 +Y）：Recast 按三角形法线坡度标记可走，法线朝下 = 不可走
        g.tris.push_back(base + 0);
        g.tris.push_back(base + 2);
        g.tris.push_back(base + 1);
        g.tris.push_back(base + 0);
        g.tris.push_back(base + 3);
        g.tris.push_back(base + 2);
    };
    auto box = [&](float x0, float z0, float x1, float z1, float y0, float y1) {
        // 六个面；法线朝向不影响（MarkWalkable 按坡角，竖直面不可走 = 障碍）
        quad(x0, z0, x1, z1, y0);
        quad(x0, z0, x1, z1, y1);
        // 侧面
        const float side[4][2][3] = {
            {{x0, y0, z0}, {x1, y0, z0}}, {{x0, y0, z1}, {x1, y0, z1}},
            {{x0, y0, z0}, {x0, y0, z1}}, {{x1, y0, z0}, {x1, y0, z1}},
        };
        for (auto& e : side) {
            const std::uint32_t base =
                static_cast<std::uint32_t>(g.verts.size() / 3);
            const float q[4][3] = {{e[0][0], y0, e[0][2]},
                                   {e[1][0], y0, e[1][2]},
                                   {e[1][0], y1, e[1][2]},
                                   {e[0][0], y1, e[0][2]}};
            for (int i = 0; i < 4; ++i)
                g.verts.insert(g.verts.end(), q[i], q[i] + 3);
            g.tris.push_back(base + 0);
            g.tris.push_back(base + 1);
            g.tris.push_back(base + 2);
            g.tris.push_back(base + 0);
            g.tris.push_back(base + 2);
            g.tris.push_back(base + 3);
        }
    };
    quad(-10, -10, 10, 10, 0.f);          // 地板
    box(-1, -1, 1, 1, 0.f, 2.f);          // 中央障碍
    quad(12, -2, 16, 2, 0.f);             // M-N1 孤立岛（与主地板隔 2m 沟，
                                          //   供 UNREACHABLE 用例）
    return g;
}

