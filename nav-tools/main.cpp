// 子命令实现
struct BakeOptions {
    nl::nav::BuildParams params;
    bool any = false;
};

bool parseBakeArgs(int argc, char** argv, int& i, BakeOptions& opt,
                   std::string& err) {
    for (; i < argc; ++i) {
        const std::string a = argv[i];
        auto need = [&](float& f, const char* name) -> bool {
            if (i + 1 >= argc) { err = std::string(name) + " needs a value"; return false; }
            f = static_cast<float>(std::atof(argv[++i]));
            return true;
        };
        if (a == "--cell-size")      { if (!need(opt.params.cellSize, a.c_str())) return false; opt.any = true; }
        else if (a == "--cell-height") { if (!need(opt.params.cellHeight, a.c_str())) return false; opt.any = true; }
        else if (a == "--slope")       { if (!need(opt.params.walkableSlopeAngle, a.c_str())) return false; opt.any = true; }
        else if (a == "--agent-height"){ if (!need(opt.params.agentHeight, a.c_str())) return false; opt.any = true; }
        else if (a == "--agent-radius"){ if (!need(opt.params.agentRadius, a.c_str())) return false; opt.any = true; }
        else if (a == "--agent-climb") { if (!need(opt.params.agentMaxClimb, a.c_str())) return false; opt.any = true; }
        else if (a == "--min-region")  { if (!need(opt.params.regionMinSize, a.c_str())) return false; opt.any = true; }
        else if (a == "--merge-region"){ if (!need(opt.params.regionMergeSize, a.c_str())) return false; opt.any = true; }
        else { err = "unknown option: " + a; return false; }
    }
    return true;
}

void printStats(const char* label, const nl::nav::NavMesh& nav,
                const std::vector<unsigned char>* fileBytes) {
    const nl::nav::BuildStats& s = nav.stats();
    std::printf("navmesh     : %s\n", label);
    std::printf("walkable tri: %d\n", s.walkableTris);
    std::printf("polys       : %d\n", s.polyCount);
    std::printf("verts       : %d\n", s.vertCount);
    std::printf("detail tris : %d\n", s.detailTriCount);
    std::printf("area        : %.2f m^2\n", s.walkableArea);
    std::printf("bounds      : (%.2f, %.2f, %.2f)-(%.2f, %.2f, %.2f)\n",
                s.bmin[0], s.bmin[1], s.bmin[2], s.bmax[0], s.bmax[1],
                s.bmax[2]);
    if (fileBytes) {
        std::printf("file bytes  : %zu\n", fileBytes->size());
        std::printf("fnv64       : %016llx\n",
                    static_cast<unsigned long long>(
                        fnv1a64(fileBytes->data(), fileBytes->size())));
    }
}

int cmdBake(int argc, char** argv) {
    if (argc < 2) { usage(); return 2; }
    const char* inPath  = argv[0];
    const char* outPath = argv[1];
    BakeOptions opt;
    std::string err;
    int i = 2;
    if (!parseBakeArgs(argc, argv, i, opt, err)) {
        std::printf("nav-tools bake: %s\n", err.c_str());
        return 2;
    }

    nl::nav::Geometry geo;
    if (!loadGeometry(inPath, geo, err)) {
        std::printf("nav-tools bake: geometry load failed: %s\n", err.c_str());
        return 1;
    }
    const int nverts = static_cast<int>(geo.verts.size() / 3);
    const int ntris  = static_cast<int>(geo.tris.size() / 3);

    nl::nav::NavMesh nav;
    if (!nav.bake(geo, opt.params, err)) {
        std::printf("nav-tools bake: bake failed: %s\n", err.c_str());
        const nl::nav::BuildStats& s = nav.stats();
        std::printf("walkable tri: %d / %d | grid %dx%d | raster spans: %d | filtered: %d | compact: %d | regions: %d\n",
                    s.walkableTris, ntris, s.gridWidth, s.gridHeight,
                    s.rasterSpans, s.filteredSpans, s.compactSpans,
                    s.regionCount);
        return 1;
    }
    if (!nav.save(outPath, err)) {
        std::printf("nav-tools bake: %s\n", err.c_str());
        return 1;
    }
    std::printf("input       : %s (%d verts, %d tris)\n", inPath, nverts, ntris);
    printStats(outPath, nav, nullptr);
    std::printf("saved       : %s\n", outPath);
    return 0;
}

int cmdDump(int argc, char** argv) {
    if (argc < 1) { usage(); return 2; }
    std::string err;
    nl::nav::NavMesh nav;
    if (!nav.load(argv[0], err)) {
        std::printf("nav-tools dump: %s\n", err.c_str());
        return 1;
    }
    const std::vector<unsigned char> bytes = readFileBytes(argv[0], err);
    printStats(argv[0], nav, &bytes);
    return 0;
}

