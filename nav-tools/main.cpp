// FNV-1a 64（对齐 audio-tools provenance 口径；逐字节比对这个更强，fnv 只做展示）
std::uint64_t fnv1a64(const unsigned char* p, size_t n) {
    std::uint64_t h = 1469598103934665603ull;
    for (size_t i = 0; i < n; ++i) {
        h ^= p[i];
        h *= 1099511628211ull;
    }
    return h;
}

std::vector<unsigned char> readFileBytes(const char* path, std::string& err) {
    std::FILE* f = std::fopen(path, "rb");
    if (!f) { err = std::string("cannot open: ") + path; return {}; }
    std::fseek(f, 0, SEEK_END);
    const long n = std::ftell(f);
    std::fseek(f, 0, SEEK_SET);
    std::vector<unsigned char> buf(static_cast<size_t>(n));
    if (n > 0 && std::fread(buf.data(), 1, static_cast<size_t>(n), f) !=
                     static_cast<size_t>(n)) {
        std::fclose(f);
        err = std::string("short read: ") + path;
        return {};
    }
    std::fclose(f);
    return buf;
}

