// selftest：合成场景锚点
// 场景 = 20x20 地板 + 中央 2x2x2 方块障碍（角色须绕行 → 中心区不可走）+
// 30° 缓坡一条（可走）。确定性锚点：两次 bake 产物逐字节一致 + roundtrip 一致。
nl::nav::Geometry syntheticScene() {
    nl::nav::Geometry g;
    auto quad = [&](float x0, float z0, float x1, float z1, float y) {
        const std::uint32_t base = static_cast<std::uint32_t>(g.verts.size() / 3);
        const float v[4][3] = {{x0, y, z0}, {x1, y, z0}, {x1, y, z1}, {x0, y, z1}};
        for (int i = 0; i < 4; ++i)
            g.verts.insert(g.verts.end(), v[i], v[i] + 3);
        // 俯视 CCW（法线 +Y）：Recast 按三角形法线坡度标记可走，法线朝下 = 不可走
        g.tris.push_back(base + 0);
        g.tris.push_back(base + 2);
        g.tris.push_back(base + 1);
        g.tris.push_back(base + 0);
        g.tris.push_back(base + 3);
        g.tris.push_back(base + 2);
    };
    auto box = [&](float x0, float z0, float x1, float z1, float y0, float y1) {
        // 六个面；法线朝向不影响（MarkWalkable 按坡角，竖直面不可走 = 障碍）
        quad(x0, z0, x1, z1, y0);
        quad(x0, z0, x1, z1, y1);
        // 侧面
        const float side[4][2][3] = {
            {{x0, y0, z0}, {x1, y0, z0}}, {{x0, y0, z1}, {x1, y0, z1}},
            {{x0, y0, z0}, {x0, y0, z1}}, {{x1, y0, z0}, {x1, y0, z1}},
        };
        for (auto& e : side) {
            const std::uint32_t base =
                static_cast<std::uint32_t>(g.verts.size() / 3);
            const float q[4][3] = {{e[0][0], y0, e[0][2]},
                                   {e[1][0], y0, e[1][2]},
                                   {e[1][0], y1, e[1][2]},
                                   {e[0][0], y1, e[0][2]}};
            for (int i = 0; i < 4; ++i)
                g.verts.insert(g.verts.end(), q[i], q[i] + 3);
            g.tris.push_back(base + 0);
            g.tris.push_back(base + 1);
            g.tris.push_back(base + 2);
            g.tris.push_back(base + 0);
            g.tris.push_back(base + 2);
            g.tris.push_back(base + 3);
        }
    };
    quad(-10, -10, 10, 10, 0.f);          // 地板
    box(-1, -1, 1, 1, 0.f, 2.f);          // 中央障碍
    quad(12, -2, 16, 2, 0.f);             // M-N1 孤立岛（与主地板隔 2m 沟，
                                          //   供 UNREACHABLE 用例）
    return g;
}

int cmdSelftest(int argc, char** argv) {
    for (int i = 0; i < argc; ++i) {
        if (std::strcmp(argv[i], "--verbose") == 0) g_verbose = true;
        else { usage(); return 2; }
    }
    std::printf("nav selftest:\n");

    // 1. 合成场景 bake 锚点
    nl::nav::Geometry geo = syntheticScene();
    nl::nav::BuildParams p; // 默认参数：radius 0.5 → 障碍周围留出走道
    nl::nav::NavMesh nav;
    std::string err;
    expectTrue(nav.bake(geo, p, err), "synthetic bake succeeds");
    if (!err.empty()) std::printf("  (%s)\n", err.c_str());
    expectTrue(nav.stats().polyCount > 0, "polys > 0");
    expectTrue(nav.stats().walkableArea > 0.f, "area > 0");
    // 障碍外圈应剩可走面（地板 400 m^2 中腐蚀 + 障碍占掉一块）
    expectTrue(nav.stats().walkableArea < 400.f,
               "area < full floor (obstacle eroded)");

    // 2. 确定性：两次 bake → save → 逐字节一致
    nl::nav::NavMesh nav2;
    err.clear();
    expectTrue(nav2.bake(geo, p, err), "second bake succeeds");
    const char* pathA = "nav-selftest-a.nnav";
    const char* pathB = "nav-selftest-b.nnav";
    expectTrue(nav.save(pathA, err), "save a");
    expectTrue(nav2.save(pathB, err), "save b");
    const std::vector<unsigned char> a = readFileBytes(pathA, err);
    const std::vector<unsigned char> b = readFileBytes(pathB, err);
    expectTrue(a.size() > 0 && a == b, "determinism: artifacts byte-identical");
    std::printf("  fnv64 a    : %016llx\n",
                static_cast<unsigned long long>(fnv1a64(a.data(), a.size())));
    std::remove(pathA);
    std::remove(pathB);

    // 3. roundtrip：save -> load -> save 逐字节一致
    const char* rt0 = "nav-selftest-rt0.nnav";
    const char* rt1 = "nav-selftest-rt1.nnav";
    expectTrue(nav.save(rt0, err), "roundtrip save 0");
    nl::nav::NavMesh loaded;
    expectTrue(loaded.load(rt0, err), "roundtrip load");
    expectTrue(loaded.stats().polyCount == nav.stats().polyCount,
               "roundtrip stats equal");
    expectTrue(loaded.save(rt1, err), "roundtrip save 1");
    const std::vector<unsigned char> r0 = readFileBytes(rt0, err);
    const std::vector<unsigned char> r1 = readFileBytes(rt1, err);
    expectTrue(r0 == r1, "roundtrip: bytes identical");
    std::remove(rt0);
    std::remove(rt1);

    // 4. 负向：空几何 / 竖墙（无水平可走面）/ 坏文件
    nl::nav::NavMesh neg;
    nl::nav::Geometry empty;
    expectTrue(!neg.bake(empty, p, err) && !err.empty(),
               "negative: empty geometry rejected");
    nl::nav::Geometry wall;
    const std::uint32_t wb = 0;
    const float wv[4][3] = {{-5, 0, 0}, {5, 0, 0}, {5, 5, 0}, {-5, 5, 0}};
    for (int i = 0; i < 4; ++i) wall.verts.insert(wall.verts.end(), wv[i], wv[i] + 3);
    wall.tris = {wb + 0, wb + 1, wb + 2, wb + 0, wb + 2, wb + 3};
    expectTrue(!neg.bake(wall, p, err) && !err.empty(),
               "negative: vertical wall only rejected");
    nl::nav::NavMesh bad;
    expectTrue(!bad.load("definitely-missing.nnav", err),
               "negative: missing file rejected");
    {
        std::FILE* f = std::fopen("nav-selftest-bad.nnav", "wb");
        if (f) {
            std::fwrite("XXXXgarbage", 1, 11, f);
            std::fclose(f);
        }
        expectTrue(!bad.load("nav-selftest-bad.nnav", err),
                   "negative: garbage magic rejected");
        std::remove("nav-selftest-bad.nnav");
    }

    // 5. M-N1 查询锚点：直连 / 绕障 / 不可达 / 节点预算 / 确定性 / 参数负向
    using QS = nl::nav::NavMesh::QueryStatus;
    {
        nl::nav::NavMesh::QueryParams qp;
        nl::nav::NavMesh::QueryResult r;
        const float s0[3] = {-8.f, 0.f, -8.f}, e0[3] = {8.f, 0.f, 8.f};
        expectTrue(nav.findPath(s0, e0, qp, r) == QS::OK,
                   "query: diagonal reachable = OK");
        const int n0 = static_cast<int>(r.waypoints.size() / 3);
        expectTrue(n0 >= 2, "query: diagonal waypoints >= 2");
        if (n0 >= 2) {
            const float dx = r.waypoints[(n0 - 1) * 3] - e0[0];
            const float dz = r.waypoints[(n0 - 1) * 3 + 2] - e0[2];
            expectTrue(dx * dx + dz * dz < 0.25f,
                       "query: last waypoint lands on end");
        }

        // 绕障：直线穿过中央障碍 → 折线 > 2 点、总长 > 直线距、避开中心区
        const float s1[3] = {-8.f, 0.f, 0.f}, e1[3] = {8.f, 0.f, 0.f};
        expectTrue(nav.findPath(s1, e1, qp, r) == QS::OK,
                   "query: around obstacle = OK");
        const int n1 = static_cast<int>(r.waypoints.size() / 3);
        float len1 = 0.f;
        for (int i = 1; i < n1; ++i) {
            const float ax = r.waypoints[(i - 1) * 3];
            const float az = r.waypoints[(i - 1) * 3 + 2];
            const float bx = r.waypoints[i * 3];
            const float bz = r.waypoints[i * 3 + 2];
            const float dx = bx - ax, dz = bz - az;
            len1 += std::sqrt(dx * dx + dz * dz);
        }
        expectTrue(n1 > 2 && len1 > 16.f,
                   "query: detour longer than straight line, >2 waypoints");
        bool entersObstacle = false;
        for (int i = 1; i + 1 < n1; ++i) {
            const float x = r.waypoints[i * 3];
            const float z = r.waypoints[i * 3 + 2];
            if (std::fabs(x) < 1.5f && std::fabs(z) < 1.5f) entersObstacle = true;
        }
        expectTrue(!entersObstacle, "query: detour avoids obstacle interior");

        // 不可达：终点在孤立岛（与主地板无连接）
        const float s2[3] = {-8.f, 0.f, 0.f}, e2[3] = {14.f, 0.f, 0.f};
        expectTrue(nav.findPath(s2, e2, qp, r) == QS::UNREACHABLE,
                   "query: disconnected island = UNREACHABLE");
        expectTrue(r.waypoints.size() >= 6,
                   "query: UNREACHABLE still returns best-effort prefix");

        // 节点预算：maxNodes=4 展不开全图走廊 → OUT_OF_NODES（detail 位实据：
        // DetourNavMeshQuery.cpp getNode 池满置 outOfNodes + partial；下限 4
        // 是封装层硬闸——上游 dtNextPow2(maxNodes/4) 在 <4 时段错误）
        nl::nav::NavMesh::QueryParams tiny;
        tiny.maxNodes = 4;
        expectTrue(nav.findPath(s0, e0, tiny, r) == QS::OUT_OF_NODES,
                   "query: tiny node budget = OUT_OF_NODES");

        // 确定性：同参数同端点两次查询 waypoints 逐点一致
        nl::nav::NavMesh::QueryResult ra, rb;
        nav.findPath(s0, e0, qp, ra);
        nav.findPath(s0, e0, qp, rb);
        expectTrue(ra.waypoints == rb.waypoints && ra.status == rb.status,
                   "query: deterministic (repeat query identical)");

        // 参数负向：预算越界（<4 踩上游段错误雷，须被硬闸拦下）/ 未初始化 mesh
        nl::nav::NavMesh::QueryParams badQp;
        badQp.maxNodes = 1;
        expectTrue(nav.findPath(s0, e0, badQp, r) == QS::INVALID_PARAM,
                   "query: maxNodes=1 rejected (upstream crash guard)");
        nl::nav::NavMesh empty;
        expectTrue(empty.findPath(s0, e0, qp, r) == QS::NOT_INITIALIZED,
                   "query: uninitialized mesh rejected");
    }

    if (g_failures == 0) {
        std::printf("nav selftest: PASS\n");
        return 0;
    }
    std::printf("nav selftest: FAIL (%d)\n", g_failures);
    return 1;
}

int cmdResave(int argc, char** argv) {
    if (argc < 2) { usage(); return 2; }
    std::string err;
    nl::nav::NavMesh nav;
    if (!nav.load(argv[0], err)) {
        std::printf("nav-tools resave: %s\n", err.c_str());
        return 1;
    }
    if (!nav.save(argv[1], err)) {
        std::printf("nav-tools resave: %s\n", err.c_str());
        return 1;
    }
    std::printf("resaved    : %s -> %s\n", argv[0], argv[1]);
    return 0;
}

