int  g_failures = 0;
bool g_verbose  = false;

void verboseOk(const char* what) {
    if (g_verbose) std::printf("  ok %s\n", what);
}

void expectTrue(bool ok, const char* what) {
    if (ok) { verboseOk(what); return; }
    std::printf("  FAIL %s\n", what);
    ++g_failures;
}

void usage() {
    std::printf("nav-tools - nl-engine P8 pathfinding tools (Recast/Detour %s, headless)\n",
                nl::nav::recastVersion());
    std::printf("usage:\n");
    std::printf("  nav-tools bake <in.glb|.nmesh> <out.nnav> [--cell-size F] [--cell-height F]\n");
    std::printf("          [--slope F] [--agent-height F] [--agent-radius F] [--agent-climb F]\n");
    std::printf("          [--min-region F] [--merge-region F]\n");
    std::printf("  nav-tools dump <in.nnav>\n");
    std::printf("  nav-tools wire <in.nnav> <out.png> [--size N]\n");
    std::printf("  nav-tools resave <in.nnav> <out.nnav>\n");
    std::printf("  nav-tools selftest [--verbose]\n");
    std::printf("exit codes: 0=PASS 1=failure 2=usage\n");
}

