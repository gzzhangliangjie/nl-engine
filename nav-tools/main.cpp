// 俯视正交线框画布（x→右，z→下，等比 + 32px 边距居中）。wire 与 query --png
// 共用同一投影口径；Bresenham 逐像素确定性遍历（M-N0 wire 口径不变）。
struct WireCanvas {
    std::vector<unsigned char> rgb;
    int   size  = 0;
    float scale = 0.f, cx = 0.f, cz = 0.f;
    int   edgeCount = 0;

    void toPx(float x, float z, int& px, int& py) const {
        px = static_cast<int>(std::lround((x - cx) * scale)) + size / 2;
        py = static_cast<int>(std::lround((z - cz) * scale)) + size / 2;
    }
    void dot(int px, int py, unsigned char r, unsigned char g, unsigned char b) {
        if (px < 0 || px >= size || py < 0 || py >= size) return;
        const size_t o = (static_cast<size_t>(py) * size + px) * 3;
        rgb[o] = r; rgb[o + 1] = g; rgb[o + 2] = b;
    }
    void line(float ax, float az, float bx, float bz,
              unsigned char r, unsigned char g, unsigned char b) {
        int x0, y0, x1, y1;
        toPx(ax, az, x0, y0);
        toPx(bx, bz, x1, y1);
        int dx = std::abs(x1 - x0), sx = x0 < x1 ? 1 : -1;
        int dy = -std::abs(y1 - y0), sy = y0 < y1 ? 1 : -1;
        int e = dx + dy;
        for (;;) {
            dot(x0, y0, r, g, b);
            if (x0 == x1 && y0 == y1) break;
            const int e2 = 2 * e;
            if (e2 >= dy) { e += dy; x0 += sx; }
            if (e2 <= dx) { e += dx; y0 += sy; }
        }
    }
    // 十字标记（半径 2px）——起/终点
    void cross(float x, float z, unsigned char r, unsigned char g,
               unsigned char b) {
        int px, py;
        toPx(x, z, px, py);
        for (int d = -2; d <= 2; ++d) {
            dot(px + d, py, r, g, b);
            dot(px, py + d, r, g, b);
        }
    }
};

bool makeWireCanvas(const nl::nav::NavMesh& nav, int size, WireCanvas& out) {
    const std::vector<nl::nav::NavMesh::Edge> edges = nav.polyEdges();
    out = WireCanvas{};
    out.edgeCount = static_cast<int>(edges.size());
    out.size      = size;
    const nl::nav::BuildStats& s = nav.stats();
    const float spanX = s.bmax[0] - s.bmin[0];
    const float spanZ = s.bmax[2] - s.bmin[2];
    const float span  = spanX > spanZ ? spanX : spanZ;
    if (span <= 0.f) return false;
    const int   margin = 32;
    out.scale = static_cast<float>(size - 2 * margin) / span;
    out.cx    = (s.bmin[0] + s.bmax[0]) * 0.5f;
    out.cz    = (s.bmin[2] + s.bmax[2]) * 0.5f;
    out.rgb.assign(static_cast<size_t>(size) * size * 3, 247);
    for (const nl::nav::NavMesh::Edge& e : edges)
        out.line(e.a[0], e.a[2], e.b[0], e.b[2], 52, 52, 52);
    return true;
}

int cmdWire(int argc, char** argv) {
    if (argc < 2) { usage(); return 2; }
    const char* inPath  = argv[0];
    const char* outPath = argv[1];
    int size = 1024;
    std::string err;
    for (int i = 2; i < argc; ++i) {
        if (std::strcmp(argv[i], "--size") == 0 && i + 1 < argc) {
            size = std::atoi(argv[++i]);
        } else {
            std::printf("nav-tools wire: unknown option: %s\n", argv[i]);
            return 2;
        }
    }
    if (size < 64 || size > 4096) {
        std::printf("nav-tools wire: --size must be in [64, 4096]\n");
        return 2;
    }

    nl::nav::NavMesh nav;
    if (!nav.load(inPath, err)) {
        std::printf("nav-tools wire: %s\n", err.c_str());
        return 1;
    }
    WireCanvas canvas;
    if (!makeWireCanvas(nav, size, canvas)) {
        std::printf("nav-tools wire: degenerate bounds\n");
        return 1;
    }
    if (canvas.edgeCount == 0) {
        std::printf("nav-tools wire: no polygons\n");
        return 1;
    }
    if (!png::write(outPath, size, size, canvas.rgb, err)) {
        std::printf("nav-tools wire: %s\n", err.c_str());
        return 1;
    }
    std::printf("input       : %s\n", inPath);
    std::printf("edges       : %d\n", canvas.edgeCount);
    std::printf("view        : top-down orthographic (x right, z down)\n");
    std::printf("canvas      : %dx%d\n", size, size);
    std::printf("saved       : %s\n", outPath);
    return 0;
}

