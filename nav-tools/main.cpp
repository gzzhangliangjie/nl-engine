    std::printf("  nav-tools wire <in.nnav> <out.png> [--size N]\n");
    std::printf("  nav-tools query <in.nnav> --start x,y,z --end x,y,z\n");
    std::printf("          [--max-nodes N] [--max-waypoints N]\n");
    std::printf("          [--half-extents x,y,z] [--png out.png]\n");
